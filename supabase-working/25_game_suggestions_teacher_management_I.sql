-- 1. 건의사항 저장 테이블

create table if not exists public.game_suggestions (
  id bigint generated by default as identity primary key,

  nickname text not null,

  category text not null
    check (
      category in (
        '버그 발생',
        '기능 추가',
        '게임 추가',
        '기타'
      )
    ),

  message text not null
    check (char_length(message) between 1 and 1000),

  resolved boolean not null default false,

  created_at timestamptz not null default now(),

  resolved_at timestamptz
);

-- 최신 건의사항을 먼저 찾기 위한 인덱스

create index if not exists game_suggestions_created_at_idx
  on public.game_suggestions (created_at desc);

-- 테이블 직접 접근은 허용하지 않고 RPC 함수로만 처리

alter table public.game_suggestions
  enable row level security;

revoke all
  on public.game_suggestions
  from public, anon, authenticated;


-- ============================================
-- 2. 사용자 건의사항 등록 함수
-- ============================================

create or replace function public.submit_game_suggestion(
  p_nickname text,
  p_category text,
  p_message text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_nickname text := btrim(coalesce(p_nickname, ''));
  v_category text := btrim(coalesce(p_category, ''));
  v_message text := btrim(coalesce(p_message, ''));
begin
  if char_length(v_nickname) < 1
     or char_length(v_nickname) > 16 then

    return jsonb_build_object(
      'ok', false,
      'message', '닉네임 정보가 올바르지 않습니다. 다시 로그인해 주세요.'
    );
  end if;

  if v_category not in (
    '버그 발생',
    '기능 추가',
    '게임 추가',
    '기타'
  ) then

    return jsonb_build_object(
      'ok', false,
      'message', '카테고리를 선택해 주세요.'
    );
  end if;

  if char_length(v_message) < 1
     or char_length(v_message) > 1000 then

    return jsonb_build_object(
      'ok', false,
      'message', '건의 내용은 1~1000자로 입력해 주세요.'
    );
  end if;

  insert into public.game_suggestions (
    nickname,
    category,
    message
  )
  values (
    v_nickname,
    v_category,
    v_message
  );

  return jsonb_build_object(
    'ok', true,
    'message', '건의사항을 접수했습니다.'
  );
end;
$$;


-- ============================================
-- 3. 교사 건의사항 조회 함수
-- ============================================

create or replace function public.teacher_get_suggestions(
  p_code text
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_suggestions jsonb;
begin
  if not public.teacher_code_valid(p_code) then
    return jsonb_build_object(
      'ok', false,
      'message', '교사 코드가 맞지 않습니다.'
    );
  end if;

  select coalesce(
    jsonb_agg(
      to_jsonb(s)
      order by s.created_at desc
    ),
    '[]'::jsonb
  )
  into v_suggestions
  from (
    select
      id,
      nickname,
      category,
      message,
      resolved,
      created_at,
      resolved_at
    from public.game_suggestions
    order by created_at desc
    limit 500
  ) s;

  return jsonb_build_object(
    'ok', true,
    'suggestions', v_suggestions
  );
end;
$$;


-- ============================================
-- 4. 교사 해결 상태 변경 함수
-- ============================================

create or replace function public.teacher_set_suggestion_resolved(
  p_code text,
  p_suggestion_id bigint,
  p_resolved boolean
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_resolved boolean := coalesce(p_resolved, false);
begin
  if not public.teacher_code_valid(p_code) then
    return jsonb_build_object(
      'ok', false,
      'message', '교사 코드가 맞지 않습니다.'
    );
  end if;

  update public.game_suggestions
  set
    resolved = v_resolved,
    resolved_at = case
      when v_resolved then now()
      else null
    end
  where id = p_suggestion_id;

  if not found then
    return jsonb_build_object(
      'ok', false,
      'message', '해당 건의사항을 찾을 수 없습니다.'
    );
  end if;

  return jsonb_build_object(
    'ok', true,
    'resolved', v_resolved
  );
end;
$$;


-- ============================================
-- 5. 함수 실행 권한 설정
-- ============================================

revoke all
  on function public.submit_game_suggestion(text, text, text)
  from public;

grant execute
  on function public.submit_game_suggestion(text, text, text)
  to anon, authenticated;


revoke all
  on function public.teacher_get_suggestions(text)
  from public;

grant execute
  on function public.teacher_get_suggestions(text)
  to anon, authenticated;


revoke all
  on function public.teacher_set_suggestion_resolved(text, bigint, boolean)
  from public;

grant execute
  on function public.teacher_set_suggestion_resolved(text, bigint, boolean)
  to anon, authenticated;

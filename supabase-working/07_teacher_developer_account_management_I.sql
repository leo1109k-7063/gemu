
-- 게임놀이터 SQL 07번
-- 계정·교사·개발자 관리 기능 확장

-- 1) 계정 구조 확장
-- 기존 계정에 고유 계정번호를 부여하고
-- 닉네임 변경 이력과 개발자 권한을 관리하도록 구현함.
-- 계정번호 자동 발급을 위한 시퀀스와 인덱스를 추가함.
-- 계정 삭제 확인코드를 저장하는 테이블을 구성함.

-- 2) 개발자 인증
-- developer_code_valid 함수를 통해
-- 입력된 개발자 코드와 저장된 해시를 비교하도록 구현함.
-- 실제 인증코드는 SQL에 기록하지 않음.

-- 3) 교사 계정 관리
-- teacher_get_accounts 함수로 전체 계정의
-- 닉네임, 코인, 계정번호, 개발자 권한,
-- 닉네임 변경 상태를 조회하도록 구현함.
-- 교사 코드 검증 후 결과를 반환함.

-- 4) 회원가입
-- 닉네임과 비밀번호를 이용한 자체 계정 생성을 구현함.
-- 비밀번호를 해시 형태로 저장하고
-- 중복 닉네임과 이전 닉네임 재사용을 제한함.
-- 현재 해당 2인자 가입 경로는 외부 실행이 차단된 구버전임.

-- 5) 로그인
-- 닉네임과 비밀번호 해시를 비교하여 로그인하도록 구현함.
-- 변경된 이전 닉네임으로 72시간 동안 로그인할 수 있도록 구현함.
-- 닉네임 변경이 요구된 계정은 대체 닉네임을 자동 발급함.
-- 후속 SQL에서 로그인 잠금 및 권한 반환 기능을 수정함.

-- 6) 교사 바로가기
-- 교사 코드 검증 후 홈페이지의
-- 교사 바로가기 표시 여부를 관리하도록 구현함.

-- 7) 개발자 계정 지정
-- 개발자 코드 검증 후 선택한 계정의
-- 개발자 권한을 지정하거나 해제하도록 구현함.
-- 당시 버전은 개발자를 한 명만 유지하는 방식이었음.
-- 이후 다중 개발자 등록이 가능하도록 변경 완료함.

-- 8) 닉네임 관리
-- 교사가 특정 계정의 닉네임 변경을 요구할 수 있도록 구현함.
-- 다음 로그인 시 대체 닉네임을 적용하도록 구성함.

-- 9) 계정 삭제 확인
-- teacher_create_delete_challenge 함수로
-- 계정 삭제에 사용할 일회성 확인코드를 발급하도록 구현함.
-- 확인코드는 해시로 저장하고 5분의 유효기간을 부여함.

-- 10) 계정 삭제
-- teacher_delete_account 함수로
-- 교사 코드, 개발자 코드, 삭제 확인코드를 검증한 뒤
-- 대상 계정 및 관련 코인 기록을 삭제하도록 구현함.
-- 복구가 필요한 경우를 대비하여 실행 전 백업이 요구됨.

-- 11) RPC 실행 권한
-- 개발자 권한 지정, 닉네임 변경,
-- 계정 삭제 등 관리자 함수의 실행 권한을 설정함.
-- 함수 내부에서 관리자 인증코드를 검증하도록 구성함.

-- 12) 버전 관리
-- 본 SQL은 계정·교사·개발자 관리 기능의 과거 확장 버전임.
-- 현재 운영 DB에는 후속 통합 SQL과 수정사항이 적용되어 있음.
-- 특히 구형 회원가입, 로그인, 단일 개발자 지정 기능은
-- 현재 운영 버전과 일치하지 않음.
-- 본 SQL 원본을 운영 DB에 재실행하지 말 것.

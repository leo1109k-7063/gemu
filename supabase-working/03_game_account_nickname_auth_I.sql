-- 보안상 코드 대신 설명으로 대
-- [일반 사용자 가입]
--   닉네임 + 비밀번호 입력
--     -> register_game_account(닉네임, 비밀번호) 함수 호출
--     -> 닉네임·비밀번호 형식 확인
--     -> 비밀번호를 pgcrypto의 crypt()로 해시화
--     -> game_profiles에 새 계정 행 생성
--     -> 생성한 계정 ID/닉네임/코인 잔액 반환
--
-- [일반 사용자 로그인]
--   닉네임 + 비밀번호 입력
--     -> login_game_account(닉네임, 비밀번호) 함수 호출
--     -> game_profiles에서 대소문자를 구분하지 않고 닉네임 검색
--     -> 저장된 password_hash를 이용해 비밀번호 일치 여부 확인
--     -> 성공하면 ID/닉네임/코인 잔액 반환
--     -> 실패하면 닉네임 또는 비밀번호가 틀렸다는 응답
--
-- [교사 기능]
--   교사 코드 입력
--     -> 각 교사 기능 함수가 teacher_code_valid()로 코드 확인
--     -> 성공 시 회원 목록 보기 / 코인 지급 / 게임 ON·OFF 설정 허용
--     -> 코드가 틀리면 기능 실행 거부
--
-- [구조적 특징]
-- - 이 시기부터 Supabase Auth의 auth.users에만 의존하는 방식이 아니라,
--   game_profiles의 자체 UUID + 닉네임 + 비밀번호 해시 방식으로 변경했다.
-- - 이때 사용자의 실제 비밀번호 원문을 DB에 저장하지 않도록 설계했다.
-- - '가입에 사용한 닉네임'이 아니라 UUID가 계정의 고유 식별자다.
-- - 과거 SQL의 설계를 설명하는 것이며, 이를 안전한 세션 인증의 완성으로
--   해석해서는 안 된다. 이후 인증·잠금·가입 제한 개선 작업이 있었다.
--
-- ============================================================================
-- 2. 과거 스키마 변경 및 테이블 역할
-- ============================================================================
--
-- [확장: pgcrypto]
-- - gen_random_uuid(), crypt(), gen_salt('bf') 등 사용을 목적으로 했다.
--
-- [public.game_profiles]
-- - 회원 계정 정보를 저장하는 기본 테이블이다.
-- - id: UUID 형식의 고유 회원 ID. 당시 auth.users에 연결되던 외래 키 제약을
--   제거하고 계정 생성 시 UUID 기본값을 생성하도록 변경했다.
-- - nickname: 회원 표시명. 소문자 변환 기준 고유 인덱스로 대소문자만 다른
--   같은 닉네임의 중복 가입을 방지했다.
-- - password_hash: 비밀번호의 해시를 저장하기 위해 추가한 text 컬럼이다.
-- - coins: 회원의 보유 코인 잔액이다(기존 테이블의 필드).
-- - created_at / updated_at: 생성 및 수정 시각이다(기존 테이블의 필드).
-- - 이 파일에는 실제 회원 닉네임, UUID, 비밀번호 해시를 넣지 않는다.
--
-- [public.game_teacher_config]
-- - 교사 인증 정보를 관리하는 단일 설정 행 성격의 테이블이다.
-- - id: boolean 키. 일반적으로 true인 하나의 설정 행을 사용한다.
-- - code_hash: 실제 교사 코드의 해시를 저장하는 필드다.
-- - 과거 원본은 초기 코드 문자열을 해시화해 삽입하는 구문을 포함했다.
-- - 실제 코드나 그 해시는 공개할 수 없으므로 이 공개 설명서에는 쓰지 않는다.
-- - 현재 운영 중인 교사 코드/해시는 과거 최초 설정값과 다를 수 있다.
-- - code_hash는 '테이블 필드 이름'이지 실제 비밀 값이 아니다.
--
-- [public.game_settings]
-- - 기존 게임 사용 설정 테이블이다.
-- - omok_enabled: 오목 활성화 여부(boolean).
-- - rummikub_enabled: 루미큐브 활성화 여부(boolean).
-- - id=true인 공통 설정 행을 읽고 갱신하는 형태였다.
--
-- [public.coin_transactions]
-- - 코인 지급·차감 등 기록을 저장하는 기존 테이블이다.
-- - profile_id: 어떤 회원의 거래인지 나타내는 계정 UUID.
-- - amount: 거래 코인 수.
-- - reason: 지급 사유. 과거 03번 교사 지급에는 'teacher_grant'가 사용됐다.
-- - 교사 코인 지급 시 잔액뿐 아니라 거래 기록에도 한 건 남겼다.
--
-- ============================================================================
-- 3. 과거 RPC 함수별 기능 명세
-- ============================================================================
--
-- [register_game_account | 인자: text, text | 반환: jsonb]
-- - 목적: 닉네임과 비밀번호로 자체 회원 계정을 생성한다.
-- - 닉네임: 앞뒤 공백을 제거한 후 길이가 1~16글자인지 검사한다.
-- - 비밀번호: 영문 대소문자와 숫자로만 구성된 4~8글자인지 검사한다.
-- - 조건에 맞으면 비밀번호를 crypt(입력값, gen_salt('bf')) 형식으로 해시화한다.
-- - game_profiles에 회원을 등록하고, 성공 시 ID/닉네임/코인을 반환한다.
-- - 고유 제약 위반 시 '이미 사용 중인 닉네임' 오류를 반환한다.
-- - 이 과거 2인자 함수에는 오늘날의 브라우저 식별값 기준 가입 횟수 제한,
--   개발자 특수코드 처리, 신규 10코인 지급 등이 포함되지 않았다.
-- - 중요: 운영 DB에서는 최신 4인자 회원가입 함수가 사용되며, 2인자
--   구형 회원가입 함수의 anon 실행 권한은 별도 차단 SQL로 회수했다.
--   따라서 이 2인자 함수를 다시 외부에 열거나 구버전을 재실행하면 안 된다.
--
-- [login_game_account | 인자: text, text | 반환: jsonb]
-- - 목적: 자체 계정의 닉네임 및 비밀번호를 대조한다.
-- - 대소문자 무시 닉네임 비교 + crypt(입력 비밀번호, 저장된 해시) 비교.
-- - 로그인 성공 시 프로필의 ID/닉네임/코인 잔액을 반환했다.
-- - 실패하면 닉네임 또는 비밀번호 오류를 반환했다.
-- - 과거 03번 자체에는 비밀번호 오입력 횟수 기록, 5회 실패 시 10분 잠금,
--   개발자 권한 정보 반환 등 이후 추가된 기능이 없었다.
-- - 이 함수의 과거 반환값이 곧 최신 로그인 방식의 전부는 아니다.
--
-- [get_game_settings | 인자: 없음 | 반환: jsonb]
-- - 목적: 오목 및 루미큐브의 활성화 상태를 읽는다.
-- - game_settings의 id=true 행을 조회하고, 값이 없으면 true를 기본값으로
--   반환했다(그 경우 실제 DB 설정이 true로 저장된다는 뜻은 아니다).
--
-- [teacher_code_valid | 인자: text | 반환: boolean]
-- - 목적: 입력된 교사 코드가 game_teacher_config.code_hash와 일치하는지 검사.
-- - crypt(입력 코드, 저장된 코드 해시) 방식으로 검증했다.
-- - 일치하면 true, 불일치 또는 설정 없음이면 false를 반환했다.
-- - 함수 인자 이름이나 crypt() 사용법은 비밀코드 자체가 아니다.
-- - 이 함수가 존재한다는 사실만으로 교사 권한이 안전하게 보장되지는 않는다.
--
-- [teacher_get_accounts | 인자: text | 반환: jsonb]
-- - 목적: 교사에게 전체 계정 목록을 보여준다.
-- - 먼저 teacher_code_valid()를 호출해 입력 코드를 검증한다.
-- - 성공 시 각 계정의 nickname, coins, created_at을 모아 최신 생성순으로 반환.
-- - 실패 시 교사 코드 오류를 반환한다.
-- - 함수 설명에는 실제 회원 목록과 개인정보를 넣지 않는다.
--
-- [teacher_grant_coins | 인자: text, text, integer | 반환: jsonb]
-- - 목적: 교사가 특정 닉네임의 회원에게 코인을 지급한다.
-- - 순서: 교사 코드 검증 -> 지급량(1~100000) 검증 -> 회원 검색
--   -> coins 증가 -> coin_transactions에 지급 내역 기록 -> 결과 반환.
-- - 계정 검색은 닉네임 대소문자를 구분하지 않았다.
-- - 회원이 없으면 오류, 성공하면 닉네임과 지급 후 잔액을 반환했다.
-- - 과거 지급 사유 값은 'teacher_grant'였다.
-- - 실제 지급 대상 계정 또는 실제 지급 내역을 이 설명서에 넣지 않는다.
--
-- [teacher_update_settings | 인자: text, boolean, boolean | 반환: jsonb]
-- - 목적: 교사가 오목과 루미큐브 사용 여부를 변경한다.
-- - 먼저 교사 코드를 검사한다.
-- - game_settings의 id=true 행에 대해 INSERT 또는 기존 행 UPDATE 방식으로
--   omok_enabled, rummikub_enabled 및 updated_at을 갱신했다.
-- - NULL 인자는 당시 true를 기본값으로 처리했다.
-- - 이후 다른 인자 구성의 함수 및 호환성 수정이 있었으므로 최신 코드와
--   과거 03번의 인자 개수를 혼동하지 않는다.
--
-- ============================================================================
-- 4. 과거 RPC의 실행 권한 및 보안 구조
-- ============================================================================
--
-- - 과거 함수들은 대부분 SECURITY DEFINER로 정의되었다.
--   즉, 호출한 사용자의 테이블 권한과 별도로 함수 소유자의 권한으로 실행될
--   수 있으므로, 함수 내부 인증 검증과 EXECUTE 권한 설정이 특히 중요하다.
-- - 원본 마지막 부분은 여러 RPC의 PUBLIC 실행 권한을 회수하고,
--   register_game_account, login_game_account, get_game_settings,
--   teacher_get_accounts, teacher_grant_coins, teacher_update_settings의
--   EXECUTE 권한을 anon 및 authenticated에 부여했다.
-- - teacher_code_valid 함수는 위 명시적인 GRANT 목록에 없었다.
-- - 여기서 anon은 '로그인하지 않은 웹 사용자가 접근할 수 있는 역할'을 뜻한다.
-- - 교사 기능 RPC는 익명 호출을 허용하되 함수 안에서 별도의 교사 코드를
--   확인하는 설계였다. 따라서 코드 유출·추측 및 호출 남용에 유의해야 한다.
-- - SQL 03번은 '현재 안전성이 검증된 완성본'이 아니다.
-- - Supabase 테이블 RLS, 함수 EXECUTE 권한, 실제 세션 인증, 소유자 검증은
--   각각 별도로 점검해야 하며, 공개 여부와 보안 안전성은 별개의 문제다.
--
